pub const Revision = enum {
    dmg_0,
    dmg_a,
    dmg_b,
    dmg_c,
};

pub const production_revision: Revision = .dmg_c;

pub const Registers = struct {
    a: u8,
    f: u8,
    b: u8,
    c: u8,
    d: u8,
    e: u8,
    h: u8,
    l: u8,
    sp: u16,
    pc: u16,
};

pub const Profile = struct {
    revision: Revision,
    registers: Registers,
    mmio: [0x80]u8,
    ie: u8,
};

pub fn profile(revision: Revision) Profile {
    var mmio = [_]u8{0xFF} ** 0x80;
    const common = [_]u8{
        0xCF, 0x00, 0x7E, 0xFF, 0xAD, 0x00, 0x00, 0xF8,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xE1,
        0x80, 0xBF, 0xF3, 0xFF, 0xBF, 0xFF, 0x3F, 0x00,
        0xFF, 0xBF, 0x7F, 0xFF, 0x9F, 0xFF, 0xBF, 0xFF,
        0xFF, 0x00, 0x00, 0xBF, 0x77, 0xF3, 0xF1, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0x91, 0x80, 0x00, 0x00, 0x0A, 0x00, 0xFF, 0xFC,
        0xFF, 0xFF, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    };
    mmio = common;
    const registers: Registers = switch (revision) {
        .dmg_0 => .{ .a = 0x01, .f = 0x00, .b = 0xFF, .c = 0x13, .d = 0x00, .e = 0xC1, .h = 0x84, .l = 0x03, .sp = 0xFFFE, .pc = 0x0100 },
        .dmg_a, .dmg_b, .dmg_c => .{ .a = 0x01, .f = 0xB0, .b = 0x00, .c = 0x13, .d = 0x00, .e = 0xD8, .h = 0x01, .l = 0x4D, .sp = 0xFFFE, .pc = 0x0100 },
    };
    if (revision == .dmg_0) {
        mmio[0x04] = 0x19;
        mmio[0x41] = 0x83;
        mmio[0x44] = 0x01;
    }
    return .{ .revision = revision, .registers = registers, .mmio = mmio, .ie = 0x00 };
}

test "production profile is explicit DMG CPU C post boot" {
    const value = profile(production_revision);
    try @import("std").testing.expectEqual(Revision.dmg_c, value.revision);
    try @import("std").testing.expectEqual(@as(u16, 0x0100), value.registers.pc);
    try @import("std").testing.expectEqual(@as(u8, 0xB0), value.registers.f);
    try @import("std").testing.expectEqual(@as(u8, 0xAD), value.mmio[0x04]);
}

test "DMG zero remains a separate revision profile" {
    const value = profile(.dmg_0);
    try @import("std").testing.expectEqual(@as(u8, 0x00), value.registers.f);
    try @import("std").testing.expectEqual(@as(u8, 0x19), value.mmio[0x04]);
    try @import("std").testing.expectEqual(@as(u8, 0x83), value.mmio[0x41]);
}
